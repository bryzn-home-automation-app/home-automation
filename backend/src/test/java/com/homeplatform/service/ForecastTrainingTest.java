package com.homeplatform.service;

import com.homeplatform.model.ForecastModel;
import com.homeplatform.repository.ForecastModelRepository;
import com.homeplatform.repository.ForecastSnapshotRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;
import java.time.DayOfWeek;
import java.time.LocalDate;
import java.util.List;
import java.util.Random;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

/** trainModel and generateForecasts against a real (H2, PostgreSQL mode) database. */
class ForecastTrainingTest {

    private static final LocalDate TODAY = LocalDate.now();
    // Synthetic house: 15 kWh base, 2 kWh per cooling degree-day, +7 on weekends,
    // and each day's miss carries half into the next.
    private static final double BASE = 15, CDD = 2, WEEKEND = 7, RHO = 0.5;

    private JdbcTemplate jdbc;
    private ForecastService service;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:forecast-" + System.nanoTime() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE hourly_electric_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "\"timestamp\" TIMESTAMP NOT NULL, usage_kwh DOUBLE NOT NULL)");
        jdbc.execute("CREATE TABLE weather_observations (observation_date DATE NOT NULL, avg_temp_f DOUBLE, "
                + "high_temp_f DOUBLE, low_temp_f DOUBLE)");
        ForecastModelRepository modelRepo = mock(ForecastModelRepository.class);
        when(modelRepo.save(any())).thenAnswer(inv -> inv.getArgument(0));
        ForecastSnapshotRepository snapshotRepo = mock(ForecastSnapshotRepository.class);
        service = new ForecastService(jdbc, modelRepo, snapshotRepo, mock(AppEventService.class));
    }

    /** One day of usage spread over {@code hours} hourly rows, plus its weather. */
    private void day(LocalDate date, double kwh, double avgTemp, int hours) {
        for (int h = 0; h < hours; h++) {
            jdbc.update("INSERT INTO hourly_electric_usage (\"timestamp\", usage_kwh) VALUES (?, ?)",
                    Timestamp.valueOf(date.atTime(h, 0)), kwh / hours);
        }
        jdbc.update("INSERT INTO weather_observations VALUES (?, ?, ?, ?)", date, avgTemp, avgTemp + 8, avgTemp - 8);
    }

    private static double expected(LocalDate date, double avgTemp) {
        boolean weekend = date.getDayOfWeek() == DayOfWeek.SATURDAY || date.getDayOfWeek() == DayOfWeek.SUNDAY;
        return BASE + CDD * Math.max(0, avgTemp - 65) + (weekend ? WEEKEND : 0);
    }

    /** 60 days ending yesterday; returns yesterday's miss. */
    private double history() {
        Random rnd = new Random(7);
        double miss = 0;
        for (int back = 60; back >= 1; back--) {
            LocalDate d = TODAY.minusDays(back);
            double temp = 70 + 20 * rnd.nextDouble();
            // sd 1.5: at 3 the fixed seed lands on weekends unluckily for 2 of the 7 weekdays
            // the test can run on, and the weekend estimate falls outside 7 ± 1.5.
            miss = RHO * miss + rnd.nextGaussian() * 1.5;
            day(d, expected(d, temp) + miss, temp, 24);
        }
        return miss;
    }

    @Test
    @DisplayName("learns weather, weekend and carry-over with no weekday or monthly multipliers")
    void learnsWeekendAndCarryOver() {
        history();
        ForecastModel m = service.trainModel();

        assertEquals(BASE, m.getIntercept().doubleValue(), 2.5, "intercept");
        assertEquals(CDD, m.getCddCoeff().doubleValue(), 0.2, "kWh per cooling degree-day");
        assertEquals(WEEKEND, m.getWeekendCoeff().doubleValue(), 1.5, "weekend kWh");
        assertEquals(RHO, m.getResidualRho().doubleValue(), 0.25, "carry-over");
        assertNull(m.getLagCoeff(), "no lag on yesterday's total");
        assertTrue(m.getSeasonalFactors().isEmpty(), "no monthly factor");
        assertEquals(60, m.getDataPointsUsed());
        // The weekday card shows weekends above weather alone.
        assertTrue(m.getDowAdjustments().get("SATURDAY") > m.getDowAdjustments().get("TUESDAY"));
        // predict() ignores the card's factors and the month: a Tuesday at 75°F is weather alone.
        double tuesday = m.getIntercept().doubleValue() + m.getCddCoeff().doubleValue() * 10;
        assertEquals(tuesday, service.predict(m, 75, DayOfWeek.TUESDAY, 10), 1e-9);
        assertEquals(tuesday, service.predict(m, 75, DayOfWeek.TUESDAY, 3, 999.0), 1e-9);
        assertEquals(tuesday + m.getWeekendCoeff().doubleValue(), service.predict(m, 75, DayOfWeek.SUNDAY, 10), 1e-9);
    }

    @Test
    @DisplayName("a day with under 18 hourly rows is left out of training")
    void skipsIncompleteDays() {
        history();
        day(TODAY.minusDays(70), 5, 80, 17);
        ForecastModel m = service.trainModel();
        assertEquals(60, m.getDataPointsUsed());
        assertEquals(TODAY.minusDays(60), m.getTrainingStart());
    }

    @Test
    @DisplayName("today's forecast adds rho x yesterday's miss; later days get less of it")
    void forecastCarriesYesterdaysMiss() {
        history();
        ForecastModel m = service.trainModel();
        double rho = m.getResidualRho().doubleValue();
        LocalDate yesterday = TODAY.minusDays(1);
        double yTemp = jdbc.queryForObject("SELECT avg_temp_f FROM weather_observations WHERE observation_date = ?",
                Double.class, yesterday);
        double yActual = jdbc.queryForObject("SELECT SUM(usage_kwh) FROM hourly_electric_usage WHERE CAST(\"timestamp\" AS DATE) = ?",
                Double.class, yesterday);
        double miss = yActual - service.predict(m, yTemp, yesterday.getDayOfWeek(), yesterday.getMonthValue());

        var out = service.generateForecasts(m, List.of(
                new ForecastService.WeatherForecastDay(TODAY, 88, 72, 80),
                new ForecastService.WeatherForecastDay(TODAY.plusDays(1), 88, 72, 80),
                new ForecastService.WeatherForecastDay(TODAY.plusDays(20), 88, 72, 80)));

        double today = service.predict(m, 80, TODAY.getDayOfWeek(), TODAY.getMonthValue());
        double tomorrow = service.predict(m, 80, TODAY.plusDays(1).getDayOfWeek(), TODAY.getMonthValue());
        double later = service.predict(m, 80, TODAY.plusDays(20).getDayOfWeek(), TODAY.getMonthValue());
        assertEquals(Math.round((today + rho * miss) * 100) / 100.0, out.get(0).predictedKwh(), 0.011);
        assertEquals(Math.round((tomorrow + rho * rho * miss) * 100) / 100.0, out.get(1).predictedKwh(), 0.011);
        assertEquals(Math.round(later * 100) / 100.0, out.get(2).predictedKwh(), 0.011, "too far out to carry anything");
    }
}
