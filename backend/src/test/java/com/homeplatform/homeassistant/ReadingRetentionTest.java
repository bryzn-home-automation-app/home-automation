package com.homeplatform.homeassistant;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Timestamp;
import java.time.Clock;
import java.time.LocalDateTime;
import java.time.ZoneOffset;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/** The thinning SQL against a real (H2, PostgreSQL mode) database. */
class ReadingRetentionTest {

    private static final LocalDateTime NOW = LocalDateTime.of(2026, 12, 1, 12, 0);

    private JdbcTemplate jdbc;
    private ReadingRetention retention;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:retention-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE thermostat_readings (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, device_id BIGINT NOT NULL, "
                + "recorded_at TIMESTAMP NOT NULL, temperature DOUBLE)");
        retention = new ReadingRetention(jdbc, Clock.fixed(NOW.toInstant(ZoneOffset.UTC), ZoneOffset.UTC));
    }

    private void reading(long device, LocalDateTime at, double temp) {
        jdbc.update("INSERT INTO thermostat_readings (device_id, recorded_at, temperature) VALUES (?, ?, ?)",
                device, Timestamp.valueOf(at), temp);
    }

    private List<Double> temps(long device) {
        return jdbc.queryForList("SELECT temperature FROM thermostat_readings WHERE device_id = ? ORDER BY recorded_at, id",
                Double.class, device);
    }

    @Test
    @DisplayName("old readings thin to each hour's last one per device; the last month stays whole")
    void thins() {
        LocalDateTime old = NOW.minusDays(40).withMinute(0);
        reading(1, old.plusMinutes(3), 70.0);
        reading(1, old.plusMinutes(30), 71.0);
        reading(1, old.plusMinutes(57), 72.0);  // kept: last of its hour
        reading(1, old.plusHours(1).plusMinutes(5), 73.0); // kept: only one in the next hour
        reading(2, old.plusMinutes(10), 60.0);
        reading(2, old.plusMinutes(40), 61.0);  // kept: device 2's own last
        LocalDateTime recent = NOW.minusDays(3).withMinute(0);
        reading(1, recent.plusMinutes(1), 80.0);
        reading(1, recent.plusMinutes(2), 81.0); // recent: both kept

        assertThat(retention.thin("thermostat_readings")).isEqualTo(3);
        assertThat(temps(1)).containsExactly(72.0, 73.0, 80.0, 81.0);
        assertThat(temps(2)).containsExactly(61.0);
        assertThat(retention.thin("thermostat_readings")).isZero(); // idempotent
    }

    @Test
    @DisplayName("two readings at the same instant keep exactly one")
    void ties() {
        LocalDateTime at = NOW.minusDays(40);
        reading(1, at, 70.0);
        reading(1, at, 70.5);
        assertThat(retention.thin("thermostat_readings")).isEqualTo(1);
        assertThat(temps(1)).containsExactly(70.5);
    }

    @Test
    @DisplayName("only the known reading tables can be thinned")
    void onlyKnownTables() {
        assertThatThrownBy(() -> retention.thin("users")).isInstanceOf(IllegalArgumentException.class);
    }
}
